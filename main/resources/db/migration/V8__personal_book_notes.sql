-- Additive. Restore pre-V8 DB+storage with writes stopped to roll back; never edit migration history.
CREATE TABLE book_notes (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    book_id bigint NOT NULL,
    owner_id integer NOT NULL,
    note_text text NOT NULL CHECK (length(note_text) BETWEEN 1 AND 2000 AND length(btrim(note_text)) > 0),
    chapter varchar(8) NOT NULL CHECK (chapter ~ '^(text|s[0-9]{1,4})$'),
    position_offset integer NOT NULL CHECK (position_offset BETWEEN 0 AND 10485760),
    fingerprint varchar(64) NOT NULL CHECK (fingerprint ~ '^[0-9a-f]{64}$'),
    representation_version integer NOT NULL CHECK (representation_version > 0),
    version integer NOT NULL DEFAULT 0 CHECK (version >= 0),
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT notes_book_owner_fk FOREIGN KEY (book_id, owner_id) REFERENCES books(id, owner_id) ON DELETE CASCADE
);
CREATE INDEX notes_book_owner_created_idx ON book_notes(book_id, owner_id, created_at DESC, id DESC);
