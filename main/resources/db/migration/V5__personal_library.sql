-- Metadata and opaque source reference. Files are managed by ingestion/cleanup, not SQL.
CREATE TABLE books (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id integer NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    title varchar(200) NOT NULL CHECK (length(btrim(title)) > 0),
    author varchar(200) NOT NULL DEFAULT '',
    format varchar(8) NOT NULL CHECK (format IN ('EPUB', 'TXT')),
    state varchar(16) NOT NULL DEFAULT 'PROCESSING' CHECK (state IN ('PROCESSING', 'READY', 'DELETING')),
    original_size bigint NOT NULL CHECK (original_size BETWEEN 1 AND 10485760),
    source_sha256 varchar(64) NOT NULL CHECK (source_sha256 ~ '^[0-9a-f]{64}$'),
    storage_key uuid NOT NULL UNIQUE,
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version bigint NOT NULL DEFAULT 0 CHECK (version >= 0),
    CONSTRAINT books_owner_source_key UNIQUE (owner_id, source_sha256)
);
CREATE INDEX books_owner_created_idx ON books (owner_id, created_at DESC, id DESC);
