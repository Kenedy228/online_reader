-- Initial schema reflects the existing JPA models; it creates no accounts or passwords.
CREATE TABLE users (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username varchar(50) NOT NULL UNIQUE,
    password varchar(60) NOT NULL,
    account_non_expired boolean NOT NULL DEFAULT true,
    account_non_locked boolean NOT NULL DEFAULT true,
    credentials_non_expired boolean NOT NULL DEFAULT true,
    enabled boolean NOT NULL DEFAULT true
);

CREATE TABLE admin (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login varchar(50) NOT NULL UNIQUE,
    password varchar(60) NOT NULL,
    account_non_expired boolean NOT NULL DEFAULT true,
    account_non_locked boolean NOT NULL DEFAULT true,
    credentials_non_expired boolean NOT NULL DEFAULT true,
    enabled boolean NOT NULL DEFAULT true
);

-- Hibernate's implicit sequence generator uses allocationSize=50.
CREATE SEQUENCE actions_seq START WITH 1 INCREMENT BY 50;
CREATE TABLE actions (
    id integer PRIMARY KEY,
    label varchar(255) NOT NULL UNIQUE,
    description varchar(255) NOT NULL UNIQUE
);

CREATE TABLE admin_actions (
    admin_id integer NOT NULL REFERENCES admin(id),
    action_id integer NOT NULL REFERENCES actions(id),
    PRIMARY KEY (admin_id, action_id)
);
CREATE INDEX admin_actions_action_id_idx ON admin_actions(action_id);
